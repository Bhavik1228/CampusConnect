import { jsPDF } from 'jspdf';
import { savePdfBlob } from './official-documents';

export type ReportLayout = 'classic' | 'modern' | 'minimal' | 'academic' | 'vibrant';

export interface SchoolReportPdfOptions {
  title: string;
  subtitle?: string;
  schoolName: string;
  schoolAddress?: string;
  footer?: string;
  accentColor?: string;
  layout?: ReportLayout;
  filename: string;
  columns: string[];
  rows: string[][];
  summary?: Array<[string, string]>;
}

const PAGE_WIDTH = 210;
const PAGE_HEIGHT = 297;
const MARGIN = 15;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2;
const NAVY: [number, number, number] = [20, 43, 73];
const INK: [number, number, number] = [31, 41, 55];
const MUTED: [number, number, number] = [82, 100, 119];
const BORDER: [number, number, number] = [217, 226, 234];
const PALE: [number, number, number] = [244, 247, 250];

function printable(value: unknown) {
  return String(value ?? '').normalize('NFKD').replace(/\p{Diacritic}/gu, '').replace(/[^\x20-\x7E]/g, ' ').replace(/\s+/g, ' ').trim();
}

function rgbFromHex(value?: string): [number, number, number] {
  const match = value?.match(/^#([0-9a-f]{6})$/i);
  if (!match) return [8, 126, 131];
  return [Number.parseInt(match[1].slice(0, 2), 16), Number.parseInt(match[1].slice(2, 4), 16), Number.parseInt(match[1].slice(4, 6), 16)];
}

export function downloadSchoolReportPdf(options: SchoolReportPdfOptions) {
  const pdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const accent = rgbFromHex(options.accentColor);
  const generated = new Intl.DateTimeFormat(undefined, { dateStyle: 'medium', timeStyle: 'short' }).format(new Date());
  let y = 0;

  const drawHeader = (pageNumber: number) => {
    const modern = options.layout === 'modern' || options.layout === 'vibrant';
    pdf.setFillColor(...(modern ? accent : NAVY));
    pdf.rect(0, 0, PAGE_WIDTH, pageNumber === 1 ? 38 : 22, 'F');
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(pageNumber === 1 ? 15 : 10);
    pdf.setTextColor(255, 255, 255);
    pdf.text(printable(options.schoolName) || 'School', MARGIN, pageNumber === 1 ? 13 : 9);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(7.5);
    pdf.setTextColor(230, 235, 242);
    pdf.text(printable(options.schoolAddress) || 'Official school report', MARGIN, pageNumber === 1 ? 19 : 15);
    if (pageNumber === 1) {
      pdf.setFont('helvetica', 'bold');
      pdf.setFontSize(11);
      pdf.setTextColor(255, 255, 255);
      pdf.text(printable(options.title).toUpperCase(), PAGE_WIDTH - MARGIN, 13, { align: 'right', maxWidth: 95 });
      if (options.subtitle) {
        pdf.setFont('helvetica', 'normal');
        pdf.setFontSize(7.5);
        pdf.text(printable(options.subtitle), PAGE_WIDTH - MARGIN, 21, { align: 'right', maxWidth: 95 });
      }
      pdf.setFontSize(7);
      pdf.text(`Generated ${generated}`, PAGE_WIDTH - MARGIN, 30, { align: 'right' });
    } else {
      pdf.text(printable(options.title), PAGE_WIDTH - MARGIN, 12, { align: 'right', maxWidth: 100 });
    }
  };

  const drawFooter = (pageNumber: number) => {
    pdf.setDrawColor(...BORDER);
    pdf.setLineWidth(0.3);
    pdf.line(MARGIN, PAGE_HEIGHT - 14, PAGE_WIDTH - MARGIN, PAGE_HEIGHT - 14);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(7);
    pdf.setTextColor(...MUTED);
    pdf.text(printable(options.footer) || 'Generated by Campus Connect', MARGIN, PAGE_HEIGHT - 9);
    pdf.text(`${pageNumber} / ${pdf.getNumberOfPages()}`, PAGE_WIDTH - MARGIN, PAGE_HEIGHT - 9, { align: 'right' });
  };

  drawHeader(1);
  y = 47;
  if (options.summary?.length) {
    const summaryWidth = (CONTENT_WIDTH - 6 * (options.summary.length - 1)) / options.summary.length;
    options.summary.forEach(([label, value], index) => {
      const x = MARGIN + index * (summaryWidth + 6);
      pdf.setFillColor(...PALE);
      pdf.roundedRect(x, y, summaryWidth, 20, 2, 2, 'F');
      pdf.setDrawColor(...BORDER);
      pdf.roundedRect(x, y, summaryWidth, 20, 2, 2, 'S');
      pdf.setFont('helvetica', 'bold');
      pdf.setFontSize(10);
      pdf.setTextColor(...accent);
      pdf.text(printable(value), x + 4, y + 8);
      pdf.setFont('helvetica', 'normal');
      pdf.setFontSize(6.5);
      pdf.setTextColor(...MUTED);
      pdf.text(printable(label).toUpperCase(), x + 4, y + 15);
    });
    y += 27;
  }

  const columnCount = options.columns.length;
  const widths = Array.from({ length: columnCount }, () => CONTENT_WIDTH / columnCount);
  if (columnCount === 5) widths.splice(0, widths.length, 30, 42, 34, 34, 40);
  if (columnCount === 6) widths.splice(0, widths.length, 24, 33, 30, 33, 30, 30);

  const tableBottom = PAGE_HEIGHT - 17;
  const drawTableHeader = () => {
    pdf.setFillColor(...NAVY);
    pdf.rect(MARGIN, y, CONTENT_WIDTH, 10, 'F');
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(7);
    pdf.setTextColor(255, 255, 255);
    let x = MARGIN;
    options.columns.forEach((column, index) => {
      pdf.text(printable(column).toUpperCase(), x + 2, y + 6.5, { maxWidth: widths[index] - 4 });
      x += widths[index];
    });
    y += 10;
  };

  drawTableHeader();
  options.rows.forEach((row, rowIndex) => {
    const wrapped = row.map((cell, index) => pdf.splitTextToSize(printable(cell) || '-', widths[index] - 4) as string[]);
    const rowHeight = Math.max(9, ...wrapped.map((lines) => lines.length * 3.7 + 4));
    if (y + rowHeight > tableBottom) {
      drawFooter(pdf.getNumberOfPages());
      pdf.addPage();
      drawHeader(pdf.getNumberOfPages());
      y = 29;
      drawTableHeader();
    }
    pdf.setFillColor(rowIndex % 2 === 0 ? 255 : 250, rowIndex % 2 === 0 ? 255 : 250, rowIndex % 2 === 0 ? 255 : 252);
    pdf.rect(MARGIN, y, CONTENT_WIDTH, rowHeight, 'F');
    pdf.setDrawColor(...BORDER);
    pdf.setLineWidth(0.2);
    pdf.line(MARGIN, y + rowHeight, PAGE_WIDTH - MARGIN, y + rowHeight);
    let x = MARGIN;
    wrapped.forEach((lines, index) => {
      pdf.setFont('helvetica', index === 0 ? 'bold' : 'normal');
      pdf.setFontSize(7);
      pdf.setTextColor(...(index === 0 ? INK : MUTED));
      pdf.text(lines, x + 2, y + 6, { maxWidth: widths[index] - 4 });
      x += widths[index];
    });
    y += rowHeight;
  });

  if (!options.rows.length) {
    pdf.setFillColor(...PALE);
    pdf.roundedRect(MARGIN, y, CONTENT_WIDTH, 26, 2, 2, 'F');
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(9);
    pdf.setTextColor(...MUTED);
    pdf.text('No records are available for this report.', PAGE_WIDTH / 2, y + 15, { align: 'center' });
  }

  const pageCount = pdf.getNumberOfPages();
  for (let page = 1; page <= pageCount; page += 1) {
    pdf.setPage(page);
    drawFooter(page);
  }
  savePdfBlob(pdf.output('blob'), options.filename);
}
